    private val dateFormatter = SimpleDateFormat("dd MMM yyyy, hh:mm a", Locale.getDefault())

    fun writePdfReport(
        outputStream: OutputStream,
        businessName: String,
        ownerName: String,
        customers: List<Customer>,
        transactions: List<LedgerTransaction>,
        titleOverride: String? = null
    ) {
        val document = PdfDocument()
        val pageWidth = 595
        val pageHeight = 842
        val margin = 36f

        val titlePaint = Paint().apply {
            color = Color.parseColor("#0F172A")
            textSize = 18f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }
        val subtitlePaint = Paint().apply {
            color = Color.parseColor("#475569")
            textSize = 10.5f
        }
        val headerBarPaint = Paint().apply {
            color = Color.parseColor("#059669")
        }
        val headerTextPaint = Paint().apply {
            color = Color.WHITE
            textSize = 10f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }
        val rowPaint = Paint().apply {
            color = Color.parseColor("#1E293B")
            textSize = 9.5f
        }
        val dividerPaint = Paint().apply {
            color = Color.parseColor("#CBD5E1")
            strokeWidth = 0.8f
        }
        val footerPaint = Paint().apply {
            color = Color.parseColor("#64748B")
            textSize = 8.5f
        }

        var pageNumber = 1
        var page = document.startPage(PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNumber).create())
        var canvas = page.canvas
        var y = 44f

        fun drawHeaderAndColumns(isFirstPage: Boolean) {
            if (isFirstPage) {
                canvas.drawText(titleOverride ?: "$businessName — Hisab-Kitab Statement", margin, y, titlePaint)
                y += 16f
                canvas.drawText(
                    "Generated by Simple SMS Calculator | Owner: $ownerName | ${dateFormatter.format(Date())}",
                    margin,
                    y,
                    subtitlePaint
                )
                y += 18f

                val totalUdhaar = customers.sumOf { it.totalUdhaarPaise }
                val totalJama = customers.sumOf { it.totalJamaPaise }
                val netBalance = totalUdhaar - totalJama
                canvas.drawText(
                    "Total Udhaar: ${LedgerRepository.formatCurrencyPaise(totalUdhaar)}   |   Total Jama: ${LedgerRepository.formatCurrencyPaise(totalJama)}   |   Net Due: ${LedgerRepository.formatCurrencyPaise(netBalance)}",
                    margin,
                    y,
                    subtitlePaint.apply { typeface = Typeface.DEFAULT_BOLD }
                )
                subtitlePaint.typeface = Typeface.DEFAULT
                y += 18f
            } else {
                canvas.drawText("$businessName — Statement (Cont.)", margin, y, subtitlePaint)
                y += 18f
            }

            canvas.drawRect(margin, y, pageWidth - margin, y + 20f, headerBarPaint)
            canvas.drawText("Date", margin + 6f, y + 13.5f, headerTextPaint)
            canvas.drawText("Customer", margin + 125f, y + 13.5f, headerTextPaint)
            canvas.drawText("Type", margin + 260f, y + 13.5f, headerTextPaint)
            canvas.drawText("Amount", margin + 325f, y + 13.5f, headerTextPaint)
            canvas.drawText("Note / Ref", margin + 415f, y + 13.5f, headerTextPaint)
            y += 28f
        }

        drawHeaderAndColumns(isFirstPage = true)

        if (transactions.isEmpty()) {
            canvas.drawText("No transactions recorded yet.", margin, y, rowPaint)
        } else {
            for (tx in transactions) {
                if (y > pageHeight - 64f) {
                    canvas.drawText(
                        "© 2026 Hardik Kumar. All Rights Reserved. | Page $pageNumber",
                        margin,
                        pageHeight - 24f,
                        footerPaint
                    )
                    document.finishPage(page)
                    pageNumber++
                    page = document.startPage(
                        PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNumber).create()
                    )
                    canvas = page.canvas
                    y = 44f
                    drawHeaderAndColumns(isFirstPage = false)
                }

                val dateText = if (tx.createdAtEpochMs > 0L) {
                    SimpleDateFormat("dd/MM/yy HH:mm", Locale.getDefault()).format(Date(tx.createdAtEpochMs))
                } else "Saved"
                val amtText = LedgerRepository.formatCurrencyPaise(tx.amountPaise)
                val noteSummary = listOf(tx.billReference, tx.note).filter { it.isNotBlank() }.joinToString(" - ")

                canvas.drawText(dateText.take(16), margin + 6f, y, rowPaint)
                canvas.drawText(tx.customerName.take(20), margin + 125f, y, rowPaint)
                canvas.drawText(tx.type, margin + 260f, y, rowPaint)
                canvas.drawText(amtText.take(14), margin + 325f, y, rowPaint)
                canvas.drawText(noteSummary.ifBlank { "-" }.take(24), margin + 415f, y, rowPaint)
                y += 6f
                canvas.drawLine(margin, y, pageWidth - margin, y, dividerPaint)
                y += 14f
            }
        }

        canvas.drawText(
            "© 2026 Hardik Kumar. All Rights Reserved. | Page $pageNumber",
            margin,
            pageHeight - 24f,
            footerPaint
        )
        document.finishPage(page)
        document.writeTo(outputStream)
        document.close()
    }

    fun writeCsvReport(
        outputStream: OutputStream,
        transactions: List<LedgerTransaction>
    ) {
        val sb = StringBuilder()
        // UTF-8 BOM for Microsoft Excel compatibility
        sb.append('\uFEFF')
        sb.appendLine("Transaction ID,Date,Customer Name,Phone,Type,Amount (INR),Bill Reference,Note,SMS Receipt Sent,SMS Method")
        for (tx in transactions) {
            val dateText = if (tx.createdAtEpochMs > 0L) dateFormatter.format(Date(tx.createdAtEpochMs)) else "Saved"
            val amountInr = String.format(Locale.US, "%.2f", tx.amountPaise / 100.0)
            sb.appendLine(
                listOf(
                    csvEscape(tx.id),
                    csvEscape(dateText),
                    csvEscape(tx.customerName),
                    csvEscape(tx.customerPhone),
                    csvEscape(tx.type),
                    amountInr,
                    csvEscape(tx.billReference),
                    csvEscape(tx.note),
                    tx.smsReceiptSent.toString(),
                    csvEscape(tx.smsMethod)
                ).joinToString(",")
            )
        }
        outputStream.write(sb.toString().toByteArray(Charsets.UTF_8))
    }

