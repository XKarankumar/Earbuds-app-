        outputStream.write(zipBytes.toByteArray())
    }

    fun exportEncryptedBackup(
        outputStream: OutputStream,
        passphrase: String,
        customers: List<Customer>,
        transactions: List<LedgerTransaction>
    ) {
        val root = JSONObject().apply {
            put("app", "Simple SMS Calculator")
            put("owner", "Hardik Kumar")
            put("exportedAtEpochMs", System.currentTimeMillis())
            put("customers", JSONArray().apply {
                customers.forEach { c ->
                    put(JSONObject().apply {
                        put("id", c.id)
                        put("name", c.name)
                        put("phone", c.phone)
                        put("notes", c.notes)
                        put("totalUdhaarPaise", c.totalUdhaarPaise)
                        put("totalJamaPaise", c.totalJamaPaise)
                        put("balancePaise", c.balancePaise)
                        put("createdAtEpochMs", c.createdAtEpochMs)
                    })
                }
            })
            put("transactions", JSONArray().apply {
                transactions.forEach { t ->
                    put(JSONObject().apply {
                        put("id", t.id)
                        put("customerId", t.customerId)
                        put("customerName", t.customerName)
                        put("customerPhone", t.customerPhone)
                        put("type", t.type)
                        put("amountPaise", t.amountPaise)
                        put("note", t.note)
                        put("billReference", t.billReference)
                        put("smsReceiptSent", t.smsReceiptSent)
                        put("smsMethod", t.smsMethod)
                        put("createdAtEpochMs", t.createdAtEpochMs)
                    })
                }
            })
        }
        val encrypted = CryptoVault.encryptPortableBackup(root.toString(), passphrase)
        outputStream.write(encrypted.toByteArray(Charsets.UTF_8))
    }

    fun parseEncryptedBackup(encryptedContent: String, passphrase: String): Result<BackupPayload> {
        val decryptedRes = CryptoVault.decryptPortableBackup(encryptedContent, passphrase)
        if (decryptedRes.isFailure) return Result.failure(decryptedRes.exceptionOrNull()!!)
        return try {
            val json = JSONObject(decryptedRes.getOrThrow())
            val cArr = json.optJSONArray("customers") ?: JSONArray()
            val tArr = json.optJSONArray("transactions") ?: JSONArray()

            val customers = buildList {
                for (i in 0 until cArr.length()) {
                    val obj = cArr.getJSONObject(i)
                    add(
                        Customer(
                            id = obj.optString("id"),
                            name = obj.optString("name"),
                            phone = obj.optString("phone"),
                            notes = obj.optString("notes"),
                            totalUdhaarPaise = obj.optLong("totalUdhaarPaise"),
                            totalJamaPaise = obj.optLong("totalJamaPaise"),
                            balancePaise = obj.optLong("balancePaise"),
                            createdAtEpochMs = obj.optLong("createdAtEpochMs", 0L)
                        )
                    )
                }
            }
            val transactions = buildList {
                for (i in 0 until tArr.length()) {
                    val obj = tArr.getJSONObject(i)
                    add(
                        LedgerTransaction(
                            id = obj.optString("id"),
                            customerId = obj.optString("customerId"),
                            customerName = obj.optString("customerName"),
                            customerPhone = obj.optString("customerPhone"),
                            type = obj.optString("type", TransactionType.UDHAAR.name),
                            amountPaise = obj.optLong("amountPaise"),
                            note = obj.optString("note"),
                            billReference = obj.optString("billReference"),
                            smsReceiptSent = obj.optBoolean("smsReceiptSent"),
                            smsMethod = obj.optString("smsMethod", SmsDispatchMethod.NONE.name),
                            createdAtEpochMs = obj.optLong("createdAtEpochMs", 0L)
                        )
                    )
                }
            }
            Result.success(BackupPayload(customers = customers, transactions = transactions))
        } catch (e: Exception) {
            Result.failure(IllegalArgumentException("Backup payload is malformed", e))
        }
    }

    fun createCacheExportFile(context: Context, fileName: String): File {
        val dir = File(context.cacheDir, "exports").apply { mkdirs() }
        return File(dir, fileName)
    }

    fun shareFile(context: Context, file: File, mimeType: String, chooserTitle: String) {
        val uri: Uri = FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            file
        )
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = mimeType
            putExtra(Intent.EXTRA_STREAM, uri)
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        val chooser = Intent.createChooser(intent, chooserTitle).apply {
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        context.startActivity(chooser)
    }

    private fun csvEscape(value: String): String {
        val escaped = value.replace("\"", "\"\"")
        return "\"$escaped\""
    }

    private sealed class CellVal {
        data class Text(val v: String) : CellVal()
        data class Num(val v: Double) : CellVal()
    }

    private fun buildXmlRow(rowIndex: Int, values: List<String>, style: Int = 0): String {
        return buildXmlRowMixed(rowIndex, values.map { CellVal.Text(it) }, style)
    }

    private fun buildXmlRowMixed(rowIndex: Int, cells: List<CellVal>, style: Int = 0): String {
        val cellsXml = cells.mapIndexed { colIdx, cell ->
            val colName = columnRef(colIdx)
            when (cell) {
                is CellVal.Text -> """<c r="$colName$rowIndex" s="$style" t="inlineStr"><is><t>${xmlEscape(cell.v)}</t></is></c>"""
                is CellVal.Num -> """<c r="$colName$rowIndex" s="$style"><v>${String.format(Locale.US, "%.2f", cell.v)}</v></c>"""
            }
        }.joinToString("")
        return """<row r="$rowIndex">$cellsXml</row>"""
    }

    private fun columnRef(index: Int): String {
        var n = index
        val sb = StringBuilder()
        while (n >= 0) {
            sb.append(('A'.code + (n % 26)).toChar())
            n = n / 26 - 1
        }
        return sb.reverse().toString()
    }

    private fun xmlEscape(value: String): String {
        return value
            .replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace("\"", "&quot;")
            .replace("'", "&apos;")
    }
